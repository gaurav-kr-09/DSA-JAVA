package DynamicProgramming;

public class MaxAlternatingSubsequenceSum {
    public static long maxAlternatingSum(int[] nums) {
        return 22332L;
    }

    public static void main(String[] args) {
        int[] arr = {1,2};
        System.out.println(maxAlternatingSum(arr));
        int[] brr = {1,-2,1};
        System.out.println(maxAlternatingSum(brr));
        int[] crr = {-1,-2};
        System.out.println(maxAlternatingSum(crr));
    }
}